def fig_uq(name, figname, mac, tag, extra_name=None):
    d = load(name)
    if d is None:
        return
    rows = [d] if extra_name is None else [d, load(extra_name)]
    rows = [r for r in rows if r is not None]
    nrow = len(rows)
    fig, axes = plt.subplots(nrow, 2, figsize=(11, 3.8 * nrow), sharey=True,
                             squeeze=False)
    panel = iter(["(a)", "(b)", "(c)", "(d)"])
    for i, dd in enumerate(rows):
        for j, key in enumerate(("init", "final")):
            ax = axes[i, j]
            x = dd["x"]
            for pref, col, lab in (("exact", "tab:blue", "exact"),
                                   ("pred", "tab:red", "PINN")):
                m, s = dd[f"{pref}_mean_{key}"], dd[f"{pref}_std_{key}"]
                ax.plot(x, m, color=col, label=lab)
                ax.fill_between(x, m - s, m + s, color=col, alpha=0.25)
            ax.set_xlabel("x")
            ax.text(0.04, 0.9, next(panel), transform=ax.transAxes,
                    fontweight="bold")
            ax.set_xlim(-8, 8)
        axes[i, 0].set_ylabel("v(x, t)")
    axes[0, 0].legend(loc="upper right", frameon=False)
    save(fig, figname)


def envelope_metrics(d, lab):
    """Mean-curve relative L2 error and the largest deviation of the
    standard-deviation curve, relative to the peak of the exact mean."""
    em, es = d[f"exact_mean_{lab}"], d[f"exact_std_{lab}"]
    pm_, ps = d[f"pred_mean_{lab}"], d[f"pred_std_{lab}"]
    mean_err = np.linalg.norm(pm_ - em) / np.linalg.norm(em)
    std_dev = np.abs(ps - es).max() / np.abs(em).max()
    return float(mean_err), float(std_dev)


def std_metrics(d, lab):
    """Relative L2 error of the standard-deviation curve, and the relative
    shortfall of the predicted value at the peak of the exact one."""
    es, ps = d[f"exact_std_{lab}"], d[f"pred_std_{lab}"]
    rel = np.linalg.norm(ps - es) / np.linalg.norm(es)
    i = int(np.argmax(es))
    return float(rel), float(1 - ps[i] / es[i])


def uq_table(mac):
    labels = {"param_A": "$A$",
              "param_B": r"$\alpha,\beta$",
              "param_C": r"$A,\alpha,\beta,x_0$ (64)",
              "param_C_wide": r"$A,\alpha,\beta,x_0$ (128)"}
    body = []
    for name, lab in labels.items():
        d = load(name)
        if d is None:
            continue
        mean_err, std_dev = envelope_metrics(d, "final")
        std_rel, std_low = std_metrics(d, "final")
        std_rel0, _ = std_metrics(d, "init")
        body.append(
            f"{lab} & ${sci(res(d, 'rel_mean'))}$ & ${sci(res(d, 'rel_max'))}$ & "
            f"${sci(mean_err)}$ & ${sci(std_rel)}$ & ${sci(std_dev)}$ & "
            f"${fixed(res(d, 'peak_pred_final'), 3)}$ & "
            f"${fixed(res(d, 'peak_exact_final'), 3)}$ \\\\")
        tag = {"param_A": "A", "param_B": "B", "param_C": "C",
               "param_C_wide": "CW"}[name]
        mac.add(f"uqRel{tag}", sci(res(d, "rel_mean")))
        mac.add(f"uqRelMax{tag}", sci(res(d, "rel_max")))
        mac.add(f"uqMeanErr{tag}", sci(mean_err))
        mac.add(f"uqStdDev{tag}", sci(std_dev))
        mac.add(f"uqStdRel{tag}", fixed(100 * std_rel, 0))
        mac.add(f"uqStdRelInit{tag}", fixed(100 * std_rel0, 0))
        mac.add(f"uqStdLow{tag}", fixed(100 * std_low, 0))
        mac.add(f"uqRelPct{tag}", fixed(100 * res(d, "rel_mean"), 1))
        mac.add(f"uqPeakPred{tag}", fixed(res(d, "peak_pred_final"), 3))
        mac.add(f"uqPeakExact{tag}", fixed(res(d, "peak_exact_final"), 3))
        diff = abs(res(d, "peak_pred_final") / res(d, "peak_exact_final") - 1)
        mac.add(f"uqPeakDiff{tag}", fixed(100 * diff, 1))
        mac.add(f"uqSeconds{tag}", f"{res(d, 'train_seconds') / 60:.0f}")
    write_tex("tab_uq.tex", "\n".join(body) + "\n")
    # earlier runs of the same cases without rescaled parameter inputs
    for name, tag in (("param_A", "A"), ("param_B", "B"), ("param_C", "C"),
                      ("param_C_wide", "CW")):
        d = load(name + "_unscaled")
        if d is not None:
            mac.add(f"uqRelUnscaled{tag}", sci(res(d, "rel_mean")))


