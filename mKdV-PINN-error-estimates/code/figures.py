"""Figures, tables and result macros for the mKdV PINN paper.

Reads the ``.npz`` files written by ``pinn_mkdv.py`` and

  * renders every figure of the paper at 300 dpi, as both ``.png`` and ``.pdf``,
    into ``figures/``;
  * writes ``tables/results.tex``, a file of LaTeX macros holding every
    number quoted in the text, and the table bodies ``tables/tab_*.tex``.

Quantitative parameters are given in the figure captions of the paper rather
than in plot titles.

Usage:
    python3 figures.py            # read code/outputs
    python3 figures.py --quick    # read code/outputs_quick (smoke test)
"""

