def load(name):
    path = os.path.join(OUTDIR, name + ".npz")
    if not os.path.exists(path):
        return None
    d = np.load(path, allow_pickle=False)
    return {k: d[k] for k in d.files}


def res(d, key):
    return float(d["res_" + key])


def soliton_runs(prefix_fn, seeds):
    runs = []
    for s in seeds:
        d = load(prefix_fn(s))
        if d is not None:
            runs.append(d)
    return runs


def amp_name(a, s):
    return f"single_s{s}" if a == 1.0 else f"amp_a{a:.1f}_s{s}"


def meq_name(n, s):
    return f"single_s{s}" if n == 20 else f"meq_n{n}_s{s}"


def stats(runs, key):
    vals = np.array([res(d, key) for d in runs])
    return vals.mean(), vals.std(ddof=1) if len(vals) > 1 else 0.0, vals


def span(stat):
    """Mean and asymmetric bars covering the range of the runs."""
    vals = np.atleast_1d(stat[2]) if len(stat) > 2 else np.atleast_1d(stat[0])
    return stat[0], (stat[0] - vals.min(), vals.max() - stat[0])


def bars(stats_list):
    m = np.array([span(st)[0] for st in stats_list])
    lo = np.array([span(st)[1][0] for st in stats_list])
    hi = np.array([span(st)[1][1] for st in stats_list])
    return m, np.vstack([lo, hi])


def save(fig, name):
    os.makedirs(FIGDIR, exist_ok=True)
    for ext in ("png", "pdf"):
        # no creation date, so that regenerated figures are byte-identical
        meta = {"CreationDate": None} if ext == "pdf" else {}
        fig.savefig(os.path.join(FIGDIR, f"{name}.{ext}"), dpi=300,
                    bbox_inches="tight", metadata=meta)
    plt.close(fig)
    print(f"  wrote {name}.png / {name}.pdf")


def fit_slope(x, y):
    if len(x) < 2:
        return float("nan"), float("nan")
    p = np.polyfit(np.log10(x), np.log10(y), 1)
    return p[0], p[1]


# ---------------------------------------------------------------------------
# Number formatting for the LaTeX macros
# ---------------------------------------------------------------------------

def sci(x, digits=2):
    """LaTeX scientific notation, e.g. 2.1\\times 10^{-3}."""
    if x == 0 or not np.isfinite(x):
        return "0"
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10**e
    if round(m, digits - 1) >= 10:
        m, e = m / 10, e + 1
    if e == 0:
        return f"{m:.{digits - 1}f}"
    return f"{m:.{digits - 1}f}\\times 10^{{{e}}}"


def pm(mean, std, digits=2):
    """mean +/- std with a common exponent."""
    if mean == 0:
        return "0"
    e = int(math.floor(math.log10(abs(mean))))
    if e == 0:
        return f"{mean:.{digits}f} \\pm {std:.{digits}f}"
    return (f"({mean / 10**e:.{digits - 1}f} \\pm {std / 10**e:.{digits - 1}f})"
            f"\\times 10^{{{e}}}")


def fixed(x, digits=2):
    return f"{x:.{digits}f}"


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value):
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path):
        with open(path, "w") as f:
            f.write("% Generated by code/figures.py from code/outputs; "
                    "do not edit by hand.\n")
            f.write("\n".join(self.lines) + "\n")
        print(f"  wrote {os.path.relpath(path, ROOT)}")


def write_tex(name, body):
    path = os.path.join(TEXDIR, name)
    with open(path, "w") as f:
        f.write("% Generated by code/figures.py; do not edit by hand.\n")
        f.write(body)
        f.write("\\bottomrule\n")
    print(f"  wrote {os.path.relpath(path, ROOT)}")


