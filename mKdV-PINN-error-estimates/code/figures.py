    keys = ("rel_v", "rel_vx", "rel_vt", "G2", "L2", "e2", "K", "E",
            "log10_bound", "rho_eff", "sup_theta", "out_bound", "E_w",
            "log10_bound_w", "kappa_b", "train_seconds", "max_weight")
    st = {k: stats(runs, k) for k in keys}
    mac.add("nSeeds", str(len(runs)))
    mac.add("singleRelV", pm(*st["rel_v"][:2]))
    mac.add("singleRelVx", pm(*st["rel_vx"][:2]))
    mac.add("singleRelVt", pm(*st["rel_vt"][:2]))
    mac.add("singleRelVMin", sci(st["rel_v"][2].min()))
    mac.add("singleRelVMax", sci(st["rel_v"][2].max()))
    mac.add("singleGtwo", pm(*st["G2"][:2]))
    mac.add("singleLtwo", pm(*st["L2"][:2]))
    mac.add("singleEtwo", pm(*st["e2"][:2]))
    mac.add("singleK", pm(*st["K"][:2]))
    mac.add("singleE", fixed(st["E"][0], 2))
    mac.add("singleEw", fixed(st["E_w"][0], 1))
    mac.add("singleBound", fixed(st["log10_bound"][0], 1))
    mac.add("singleBoundw", fixed(st["log10_bound_w"][0], 1))
    mac.add("singleRho", fixed(st["rho_eff"][0], 2))
    mac.add("singleSupTheta", fixed(st["sup_theta"][0], 3))
    mac.add("singleOutBound", fixed(st["out_bound"][0], 2))
    mac.add("singleKappa", fixed(st["kappa_b"][0], 1))
    mac.add("singleMinutes", f"{st['train_seconds'][0] / 60:.0f}")
    mac.add("singleMaxWeight", fixed(st["max_weight"][0], 1))
    rows = []
    for i, d in enumerate(runs):
        rows.append(
            f"{i} & ${sci(res(d, 'rel_v'))}$ & ${sci(res(d, 'rel_vx'))}$ & "
            f"${sci(res(d, 'rel_vt'))}$ & ${sci(res(d, 'G2'))}$ & "
            f"${sci(res(d, 'L2'))}$ & ${fixed(res(d, 'sup_theta'), 3)}$ & "
            f"${fixed(res(d, 'out_bound'), 2)}$ \\\\")
    rows.append("\\midrule")
    rows.append(
        f"mean & ${sci(st['rel_v'][0])}$ & ${sci(st['rel_vx'][0])}$ & "
        f"${sci(st['rel_vt'][0])}$ & ${sci(st['G2'][0])}$ & "
        f"${sci(st['L2'][0])}$ & ${fixed(st['sup_theta'][0], 3)}$ & "
        f"${fixed(st['out_bound'][0], 2)}$ \\\\")
    rows.append(
        f"std & ${sci(st['rel_v'][1])}$ & ${sci(st['rel_vx'][1])}$ & "
        f"${sci(st['rel_vt'][1])}$ & ${sci(st['G2'][1])}$ & "
        f"${sci(st['L2'][1])}$ & ${fixed(st['sup_theta'][1], 3)}$ & "
        f"${fixed(st['out_bound'][1], 2)}$ \\\\")
    write_tex("tab_single.tex", "\n".join(rows) + "\n")


