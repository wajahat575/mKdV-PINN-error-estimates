def fig_error_vs_loss(d, mac):
    h = d["history"]   # columns: iteration, L^2, err_v, err_vx, err_vt
    L = np.sqrt(h[:, 1])
    fig, ax = plt.subplots(figsize=(5.6, 4.4))
    labels = [r"$v$", r"$v_x$", r"$v_t$"]
    marks = ["o", "s", "^"]
    # fit over the part of the trajectory after the initial transient
    start = min(500, int(0.2 * h[:, 0].max()))
    sel = h[:, 0] >= start
    slopes = []
    for j, (lab, mk) in enumerate(zip(labels, marks)):
        ax.loglog(L, h[:, 2 + j], mk, ms=3, alpha=0.7, label=lab)
        s, c = fit_slope(L[sel], h[sel, 2 + j])
        slopes.append(s)
        xx = np.array([L[sel].min(), L[sel].max()])
        ax.loglog(xx, 10**c * xx**s, "-", color=ax.lines[-1].get_color(),
                  lw=1.0)
    lo, hi = L[sel].min(), L.max()
    ref = np.array([lo, hi])
    y0 = h[sel, 2].min()
    ax.loglog(ref, y0 * ref / lo, "k--", lw=1.2, label="slope 1")
    ax.set_xlabel(r"training loss $\mathcal{L}(\theta,S)$")
    ax.set_ylabel("relative $L^2$ error")
    ax.legend(frameon=False, loc="lower right")
    save(fig, "fig2_error_vs_loss")
    for name, s in zip(("V", "Vx", "Vt"), slopes):
        mac.add(f"slopeLoss{name}", fixed(s, 2))
    mac.add("slopeLossFromIter", str(start))
    mac.add("historyPoints", str(int(sel.sum())))


def fig_quadrature(mac):
    rows = []
    for n in MEQ_NT:
        runs = soliton_runs(lambda s: meq_name(n, s), range(3))
        if not runs:
            continue
        M = 20 * n * n
        r = {"M": M, "n": len(runs)}
        for key in ("rel_v", "rel_vx", "rel_vt", "G2", "L2"):
            r[key] = stats(runs, key)
        gaps = np.array([abs(res(d, "G2") - res(d, "L2")) for d in runs])
        r["gap"] = (gaps.mean(), gaps.std(ddof=1) if len(gaps) > 1 else 0,
                    gaps)
        rows.append(r)
    if not rows:
        return
    M = np.array([r["M"] for r in rows], dtype=float)
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.3))
    ax = axes[0]
    for key, lab, mk in (("rel_v", r"$v$", "o"), ("rel_vx", r"$v_x$", "s"),
                         ("rel_vt", r"$v_t$", "^")):
        m, yerr = bars([r[key] for r in rows])
        ax.errorbar(M, m, yerr=yerr, fmt=mk + "-", ms=5, capsize=3, label=lab)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"number of equation points $M_{\mathrm{eq}}$")
    ax.set_ylabel("relative $L^2$ error")
    ax.text(0.04, 0.92, "(a)", transform=ax.transAxes, fontweight="bold")
    ax.legend(frameon=False)
    ax = axes[1]
    for key, lab, mk in (("G2", r"$\mathcal{G}(\theta^*)^2$", "o"),
                         ("L2", r"$\mathcal{L}(\theta^*,S)^2$", "s"),
                         ("gap", r"$|\mathcal{G}^2-\mathcal{L}^2|$", "D")):
        m, yerr = bars([r[key] for r in rows])
        ax.errorbar(M, m, yerr=yerr, fmt=mk + "-", ms=5, capsize=3, label=lab)
    gap = np.array([r["gap"][0] for r in rows])
    sg, cg = fit_slope(M, gap)
    ax.loglog(M, gap[0] * (M / M[0]) ** (-1.0), "k--", lw=1.2,
              label=r"$\propto M_{\mathrm{eq}}^{-1}$")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"number of equation points $M_{\mathrm{eq}}$")
    ax.text(0.04, 0.92, "(b)", transform=ax.transAxes, fontweight="bold")
    ax.legend(frameon=False, fontsize=9, loc="lower left")
    save(fig, "fig3_quadrature_sweep")
    # slopes of the error over the whole range and the first half
    ev = np.array([r["rel_v"][0] for r in rows])
    s_all, _ = fit_slope(M, ev)
    half = M <= 1700
    s_first, _ = fit_slope(M[half], ev[half])
    s_last, _ = fit_slope(M[M >= 3000], ev[M >= 3000])
    mac.add("slopeGapMeq", fixed(sg, 2))
    mac.add("slopeErrMeqAll", fixed(s_all, 2))
    mac.add("slopeErrMeqFirst", fixed(s_first, 2))
    mac.add("slopeErrMeqLast", fixed(s_last, 2))
    mac.add("MeqMin", f"{int(M.min())}")
    mac.add("MeqMax", f"{int(M.max())}")
    mac.add("MeqList", ", ".join(str(int(m)) for m in M))
    body = []
    for r in rows:
        body.append(
            f"{r['M']} & ${pm(*r['rel_v'][:2])}$ & ${pm(*r['G2'][:2])}$ & "
            f"${pm(*r['L2'][:2])}$ & ${pm(*r['gap'][:2])}$ \\\\")
    write_tex("tab_quadrature.tex", "\n".join(body) + "\n")
    for r in rows:
        mac.add(f"relVMeq{roman(r['M'])}", f"{sci(r['rel_v'][0])}")


def roman(n):
    """Map an integer to letters so it can appear in a macro name."""
    return "".join("ABCDEFGHIJ"[int(c)] for c in str(n))


